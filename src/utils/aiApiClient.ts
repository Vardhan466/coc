export async function fetchPracticeQuestionPool(filters?: {
  category?: ExamCategory | 'all';
  subject?: SubjectTag | 'all';
  difficulty?: 'easy' | 'medium' | 'hard' | 'all';
}): Promise<AIMCQQuestion[]> {
  const params = new URLSearchParams();
  if (filters?.category && filters.category !== 'all') params.set('category', filters.category);
  if (filters?.subject && filters.subject !== 'all') params.set('subject', filters.subject);
  if (filters?.difficulty && filters.difficulty !== 'all') params.set('difficulty', filters.difficulty);
  const qs = params.toString();
  const res = await fetch(`/api/practice/questions${qs ? `?${qs}` : ''}`);
  if (!res.ok) throw new Error('Failed to load practice question pool');
  const data = (await res.json()) as { questions: AIMCQQuestion[] };
  return data.questions || [];
}

