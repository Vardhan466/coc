export async function fetchDailyKeySheetServer(date?: string) {
  const headers = await getAdminHeaders();
  const qs = date ? `?date=${encodeURIComponent(date)}` : '';
  const res = await fetch(`/api/daily-exam/key${qs}`, { headers });
  const data = (await res.json()) as {
    locked?: boolean;
    error?: string;
    releaseTimeIST?: string;
    questions?: AIMCQQuestion[];
    title?: string;
    examDate?: string;
  };
  if (!res.ok) {
    return {
      locked: true,
      releaseTimeIST: data.releaseTimeIST || '20:00',
      error: data.error || 'Answer key is locked until release time.',
      questions: [],
    };
  }
  return {
    locked: false,
    releaseTimeIST: data.releaseTimeIST || '20:00',
    questions: data.questions || [],
    title: data.title,
    examDate: data.examDate,
  };
}

