function normalizeTopicLabel(topic: string): string {
  return topic.trim().toLowerCase().replace(/\s+/g, ' ');
}

function mapDefaultExamCategory(subject: SubjectTag, index: number): ExamCategory {
  if (subject === 'Quantitative Aptitude') {
    return index % 2 === 0 ? 'SSC' : 'Banking';
  }
  if (subject === 'Reasoning & Intelligence') {
    return index % 2 === 0 ? 'RRB NTPC' : 'SI';
  }
  if (subject === 'General Awareness') {
    return index % 3 === 0 ? 'UPSC' : index % 3 === 1 ? 'APPSC' : 'TSPSC';
  }
  return 'General Competitive Examinations';
}

