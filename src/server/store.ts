export function addAdminRule(rule: string): string[] {
  const trimmed = rule.trim();
  const state = loadStoreState();
  if (!Array.isArray(state.adminRules)) {
    state.adminRules = [];
  }
  if (trimmed && !state.adminRules.includes(trimmed)) {
    state.adminRules = [...state.adminRules, trimmed];
    saveStoreState(state);
  }
  return state.adminRules;
}

