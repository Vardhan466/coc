export function getTopicPoolAdminSnapshot(nowMs: number = Date.now()): AdminTopicsOverview {
  const todayIst = getTodayIsoDateIST(nowMs);
  const tomorrowIst = shiftIsoDate(todayIst, 1);
  const todayTopic = getTodayStudyPlanDay(nowMs);
  const nextDayTopic = getNextDayStudyPlanDay(nowMs);
  const state = loadStoreState();
  const todayPaper = state.dailyPapers[todayIst];
  const todayPaperAiCount = todayPaper
    ? todayPaper.questions.filter(
        (q) => (q as Partial<AIMCQQuestion>).sourceType === 'ai_generated'
      ).length
    : 0;
  const todayGenerationMeta = state.dailyPaperGenerationMeta?.[todayIst] || null;

  return {
    stats: getTopicPoolStats(),
    todayIst,
    tomorrowIst,
    todayTopic,
    nextDayTopic,
    dailyTopicHistory: { ...(state.dailyTopicHistory || {}) },
    usedTopicKeys: [...(state.usedTopicKeys || [])],
    todayPaperGenerated: Boolean(
      todayPaper &&
        todayPaper.questions.length > 0 &&
        (todayPaperAiCount > 0 || (todayGenerationMeta?.aiGeneratedCount || 0) > 0)
    ),
    todayPaperQuestionCount: todayPaper?.questions?.length || 0,
    todayPaperAiCount,
    autoGenerateDailyExam: state.aiConfig.autoGenerateDailyExam,
    todayGenerationMeta,
  };
}

export function resetTopicPoolCycle(preserveActiveDates = true): AdminTopicsOverview {
  const state = loadStoreState();
  const todayIst = getTodayIsoDateIST();
  const tomorrowIst = shiftIsoDate(todayIst, 1);

  if (preserveActiveDates) {
    const activeKeys: string[] = [];
    if (state.dailyTopicHistory?.[todayIst]) activeKeys.push(state.dailyTopicHistory[todayIst]);
    if (state.dailyTopicHistory?.[tomorrowIst] && !activeKeys.includes(state.dailyTopicHistory[tomorrowIst])) {
      activeKeys.push(state.dailyTopicHistory[tomorrowIst]);
    }
    state.usedTopicKeys = activeKeys;
  } else {
    state.usedTopicKeys = [];
    state.dailyTopicHistory = {};
  }
  state.topicCycleCount = (state.topicCycleCount || 1) + 1;
  saveStoreState(state);
  return getTopicPoolAdminSnapshot();
}

/**
 * Ensures there is one deterministic, shared daily exam paper per IST date assembled strictly from approved pool questions.
 */
export function buildOrGetDailyExamForDate(
  istDate: string = getTodayIsoDateIST(),
  forceRebuild = false
): TestPaper {
  const state = loadStoreState();
  const existing = state.dailyPapers[istDate];
  const cfg = state.scheduleConfig;

  const todayPlan =
    getOrAssignDailyTopicForDate(istDate) ||
    resolveCurrentStudyDay(
      cfg.cohortStartDate,
      Date.parse(`${istDate}T08:00:00Z`),
      state.syllabusOverrides,
      istDate
    );

  const pinnedIds = todayPlan.dailyMcqIds || [];
  const pinnedIdSet = new Set(pinnedIds);
  const existingHasPinned =
    pinnedIds.length === 0 ||
    (existing &&
      pinnedIds.some((pid) => existing.questions.some((eq) => eq.id === pid)));

  if (
    existing &&
    !forceRebuild &&
    existingHasPinned &&
    existing.questions.length === cfg.totalQuestions &&
    existing.description?.includes(todayPlan.topic)
  ) {
    if (/Week \d+ Day \d+/i.test(existing.title) || /100-Week Plan Focus:/i.test(existing.description || '')) {
      existing.title = 'All-India Daily Exam';
      existing.description = (existing.description || '').replace(/100-Week Plan Focus:/gi, 'Daily Exam Focus:');
      saveStoreState(state);
    }
    return existing;
  }

  const approvedPool = state.questionPool.filter((q) => q.reviewStatus === 'approved');
  const normTopic = normalizeTopicLabel(todayPlan.topic);
  const topicWords = normTopic
    .split(/[^a-z0-9]+/)
    .filter((w) => w.length >= 4);

  // 1. Explicitly generated/pinned dailyMcqIds first (preserving generation order), then AI topic matches
  const pinnedMatched = approvedPool.filter((q) => pinnedIdSet.has(q.id));
  const aiTopicMatched = approvedPool.filter(
    (q) =>
      !pinnedIdSet.has(q.id) &&
      q.sourceType === 'ai_generated' &&
      (normalizeTopicLabel(q.topic) === normTopic ||
        normalizeTopicLabel(q.topic).includes(normTopic))
  );
  const exactTopicMatched = [
    ...pinnedMatched,
    ...aiTopicMatched,
    ...approvedPool.filter(
      (q) =>
        !pinnedIdSet.has(q.id) &&
        q.sourceType !== 'ai_generated' &&
        (normalizeTopicLabel(q.topic) === normTopic ||
          normalizeTopicLabel(q.topic).includes(normTopic))
    ),
  ];
  // 2. Keyword + same subject matches
  const keywordSubjectMatched = approvedPool.filter(
    (q) =>
      !exactTopicMatched.some((m) => m.id === q.id) &&
      (q.subject === todayPlan.subject ||
        topicWords.some((w) => normalizeTopicLabel(q.topic).includes(w)))
  );
  // 3. Remaining approved questions to guarantee full paper count
  const restApproved = approvedPool.filter(
    (q) =>
      !exactTopicMatched.some((m) => m.id === q.id) &&
      !keywordSubjectMatched.some((m) => m.id === q.id)
  );

  const { unique } = deduplicateQuestions(
    [...exactTopicMatched, ...keywordSubjectMatched, ...restApproved],
    []
  );
  const targetCount = Math.max(10, Math.min(50, cfg.totalQuestions || 30));
  const selectedQuestions: Question[] = unique.slice(0, targetCount).map((q, idx) => ({
    ...q,
    qIndex: idx,
  }));

  const paper: TestPaper = {
    id: `daily_${istDate}`,
    testCode: `COC-DAILY-${istDate}`,
    title: 'All-India Daily Exam',
    description: `Daily Exam Focus: ${todayPlan.topic} (${todayPlan.subject}). Strict forward-only CBT protocol.`,
    date: istDate,
    windowStart: cfg.examStartTime,
    windowEnd: cfg.examEndTime,
    answerKeyReleaseTime: cfg.answerKeyReleaseTime,
    totalQuestions: selectedQuestions.length,
    totalDurationSeconds: cfg.examDurationSeconds,
    questionDurationSeconds: cfg.questionDurationSeconds,
    status: existing?.status || 'scheduled',
    questions: selectedQuestions,
    lockedForEditing: true,
    totalSubscribers: 4850,
    dataSource: 'local',
    category: todayPlan.recommendedExamCategories[0] || 'General Competitive Examinations',
  };

  state.dailyPapers[istDate] = paper;
  saveStoreState(state);
  return paper;
}

export function getScheduledTests(): TestPaper[] {
  const state = loadStoreState();
  return Array.isArray(state.scheduledTests) ? state.scheduledTests : [];
}

export function addScheduledTest(paper: TestPaper): TestPaper {
  const state = loadStoreState();
  if (!Array.isArray(state.scheduledTests)) {
    state.scheduledTests = [];
  }
  const existingIdx = state.scheduledTests.findIndex((t) => t.id === paper.id);
  if (existingIdx >= 0) {
    state.scheduledTests[existingIdx] = paper;
  } else {
    state.scheduledTests = [paper, ...state.scheduledTests];
  }
  saveStoreState(state);
  return paper;
}

export function deleteScheduledTest(id: string): boolean {
  const state = loadStoreState();
  if (!Array.isArray(state.scheduledTests)) {
    return false;
  }
  const beforeCount = state.scheduledTests.length;
  state.scheduledTests = state.scheduledTests.filter(
    (t) => t.id !== id && t.testCode !== id
  );
  const deleted = state.scheduledTests.length < beforeCount;
  if (deleted) {
    saveStoreState(state);
  }
  return deleted;
}

