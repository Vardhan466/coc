export function checkAndReserveRateLimit(): { allowed: boolean; reason?: string } {
  const state = loadStoreState();
  const nowMs = Date.now();
  const todayIst = getTodayIsoDateIST(nowMs);

  while (MINUTE_REQUEST_TIMESTAMPS.length > 0 && nowMs - MINUTE_REQUEST_TIMESTAMPS[0] > 60_000) {
    MINUTE_REQUEST_TIMESTAMPS.shift();
  }

  if (MINUTE_REQUEST_TIMESTAMPS.length >= state.aiConfig.perMinuteLimit) {
    return {
      allowed: false,
      reason: `Per-minute AI quota reached (${state.aiConfig.perMinuteLimit} req/min). Please retry shortly.`,
    };
  }

  const usedToday = state.dailyRequestCounts[todayIst] || 0;
  if (usedToday >= state.aiConfig.dailyRequestLimit) {
    return {
      allowed: false,
      reason: `Daily AI request limit reached (${state.aiConfig.dailyRequestLimit} req/day).`,
    };
  }

  MINUTE_REQUEST_TIMESTAMPS.push(nowMs);
  state.dailyRequestCounts[todayIst] = usedToday + 1;
  saveStoreState(state);
  return { allowed: true };
}

export function appendUsageLog(entry: Omit<AIUsageLog, 'id' | 'timestamp'>): AIUsageLog {
  const state = loadStoreState();
  const record: AIUsageLog = {
    id: `log_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`,
    timestamp: new Date().toISOString(),
    ...entry,
  };
  state.usageLogs = [record, ...state.usageLogs].slice(0, 150);
  if (entry.status === 'success') {
    state.lastSuccessfulCallAt = record.timestamp;
    state.lastError = undefined;
  } else {
    state.lastError = entry.message || 'AI operation error';
  }
  saveStoreState(state);
  return record;
}

export function updateAIConfig(patch: Partial<AIProviderConfig>): AIProviderConfig {
  const state = loadStoreState();
  const groqModels: AIModelOption[] = [
    'openai/gpt-oss-120b',
    'openai/gpt-oss-20b',
    'qwen/qwen3.8-27b',
  ];
  const geminiModels: AIModelOption[] = [
    'gemini-3.8-flash',
    'gemini-flash-latest',
    'gemini-3.1-flash-lite',
  ];
  const allowedModels: AIModelOption[] = [...groqModels, ...geminiModels];

  const nextModel =
    patch.model && allowedModels.includes(patch.model)
      ? patch.model
      : state.aiConfig.model;

  let nextProvider: AIProviderType =
    patch.provider === 'groq' || patch.provider === 'gemini'
      ? patch.provider
      : state.aiConfig.provider;

  if (patch.model && allowedModels.includes(patch.model)) {
    nextProvider = geminiModels.includes(patch.model) ? 'gemini' : 'groq';
  } else if (patch.provider && patch.provider !== state.aiConfig.provider) {
    if (patch.provider === 'groq' && !groqModels.includes(nextModel)) {
      state.aiConfig.model = 'openai/gpt-oss-120b';
    } else if (patch.provider === 'gemini' && !geminiModels.includes(nextModel)) {
      state.aiConfig.model = 'gemini-3.8-flash';
    }
  }

  const resolvedModel =
    nextProvider === 'groq' && !groqModels.includes(nextModel)
      ? 'openai/gpt-oss-120b'
      : nextProvider === 'gemini' && !geminiModels.includes(nextModel)
      ? 'gemini-3.8-flash'
      : nextModel;

  state.aiConfig = {
    ...state.aiConfig,
    provider: nextProvider,
    model: resolvedModel,
    dailyRequestLimit:
      typeof patch.dailyRequestLimit === 'number' &&
      patch.dailyRequestLimit >= 5 &&
      patch.dailyRequestLimit <= 10000
        ? Math.round(patch.dailyRequestLimit)
        : state.aiConfig.dailyRequestLimit,
    perMinuteLimit:
      typeof patch.perMinuteLimit === 'number' &&
      patch.perMinuteLimit >= 1 &&
      patch.perMinuteLimit <= 120
        ? Math.round(patch.perMinuteLimit)
        : state.aiConfig.perMinuteLimit,
    retryAttempts:
      typeof patch.retryAttempts === 'number' &&
      patch.retryAttempts >= 0 &&
      patch.retryAttempts <= 5
        ? Math.round(patch.retryAttempts)
        : state.aiConfig.retryAttempts,
    autoGenerateDailyExam:
      typeof patch.autoGenerateDailyExam === 'boolean'
        ? patch.autoGenerateDailyExam
        : state.aiConfig.autoGenerateDailyExam,
    autoGenerateQotd:
      typeof patch.autoGenerateQotd === 'boolean'
        ? patch.autoGenerateQotd
        : state.aiConfig.autoGenerateQotd,
    updatedAt: new Date().toISOString(),
  };

  saveStoreState(state);
  return state.aiConfig;
}

/**
 * Randomly selects and persists one unused topic from the 500-topic pool for the given IST date.
 * Guarantees topics NEVER repeat until all 500 slots in the current cycle are completed.
 */
export function getOrAssignDailyTopicForDate(
  istDate: string,
  options?: { forceReroll?: boolean; targetDayKey?: string }
): StudyPlanDay {
  const state = loadStoreState();
  const fullPlan = generate100WeekSyllabus(state.syllabusOverrides);

  if (!state.dailyTopicHistory) {
    state.dailyTopicHistory = {};
  }
  if (!Array.isArray(state.usedTopicKeys)) {
    state.usedTopicKeys = [];
  }

  // 1. Respect explicit admin scheduledDateOverride unless forcing reroll with another targetDayKey
  if (!options?.targetDayKey && !options?.forceReroll) {
    const scheduledMatch = fullPlan.find((d) => d.scheduledDateOverride === istDate);
    if (scheduledMatch) {
      let changed = false;
      if (state.dailyTopicHistory[istDate] !== scheduledMatch.dayKey) {
        state.dailyTopicHistory[istDate] = scheduledMatch.dayKey;
        changed = true;
      }
      if (!state.usedTopicKeys.includes(scheduledMatch.dayKey)) {
        state.usedTopicKeys = [...state.usedTopicKeys, scheduledMatch.dayKey];
        changed = true;
      }
      if (changed) saveStoreState(state);
      return scheduledMatch;
    }
  }

  // 2. If admin pinned an explicit topic key for this date
  if (options?.targetDayKey) {
    const pinned = fullPlan.find((d) => d.dayKey === options.targetDayKey);
    if (pinned) {
      state.dailyTopicHistory[istDate] = pinned.dayKey;
      if (!state.usedTopicKeys.includes(pinned.dayKey)) {
        state.usedTopicKeys = [...state.usedTopicKeys, pinned.dayKey];
      }
      saveStoreState(state);
      return pinned;
    }
  }

  // 3. Return already assigned topic for this IST date unless re-rolling
  const existingKey = state.dailyTopicHistory[istDate];
  if (existingKey && !options?.forceReroll) {
    const found = fullPlan.find((d) => d.dayKey === existingKey);
    if (found) {
      if (!state.usedTopicKeys.includes(found.dayKey)) {
        state.usedTopicKeys = [...state.usedTopicKeys, found.dayKey];
        saveStoreState(state);
      }
      return found;
    }
  }

  // 4. Filter unused pool (exclude usedTopicKeys & keys already reserved for other dates)
  const reservedKeys = new Set<string>([
    ...state.usedTopicKeys,
    ...Object.entries(state.dailyTopicHistory)
      .filter(([d]) => d !== istDate)
      .map(([, k]) => k),
  ]);

  if (options?.forceReroll && existingKey) {
    reservedKeys.add(existingKey);
  }

  let unusedCandidates = fullPlan.filter((d) => !reservedKeys.has(d.dayKey));

  // If all 500 topics are exhausted in this cycle, start a fresh cycle cleanly
  if (unusedCandidates.length === 0) {
    const stillReservedOtherDates = new Set(
      Object.entries(state.dailyTopicHistory)
        .filter(([d]) => d !== istDate)
        .map(([, k]) => k)
    );
    state.usedTopicKeys = Array.from(stillReservedOtherDates);
    state.topicCycleCount = (state.topicCycleCount || 1) + 1;
    unusedCandidates = fullPlan.filter(
      (d) => !stillReservedOtherDates.has(d.dayKey) && d.dayKey !== existingKey
    );
    if (unusedCandidates.length === 0) {
      unusedCandidates = fullPlan;
    }
  }

  // Prefer topics whose normalized title hasn't also appeared in reserved keys (handles 3 cross-week duplicate titles)
  const usedTitleSet = new Set(
    fullPlan
      .filter((d) => reservedKeys.has(d.dayKey))
      .map((d) => normalizeTopicLabel(d.topic))
  );
  const titleUniqueCandidates = unusedCandidates.filter(
    (d) => !usedTitleSet.has(normalizeTopicLabel(d.topic))
  );
  const pickPool = titleUniqueCandidates.length > 0 ? titleUniqueCandidates : unusedCandidates;

  const picked = pickPool[crypto.randomInt(pickPool.length)];
  state.dailyTopicHistory[istDate] = picked.dayKey;
  if (!state.usedTopicKeys.includes(picked.dayKey)) {
    state.usedTopicKeys = [...state.usedTopicKeys, picked.dayKey];
  }
  saveStoreState(state);
  return picked;
}

export function getTodayStudyPlanDay(nowMs: number = Date.now()): StudyPlanDay {
  const todayIst = getTodayIsoDateIST(nowMs);
  return getOrAssignDailyTopicForDate(todayIst);
}

export function getNextDayStudyPlanDay(nowMs: number = Date.now()): StudyPlanDay {
  const todayIst = getTodayIsoDateIST(nowMs);
  // Guarantee today's topic is assigned before tomorrow's so they are always distinct
  getOrAssignDailyTopicForDate(todayIst);
  const tomorrowIst = shiftIsoDate(todayIst, 1);
  return getOrAssignDailyTopicForDate(tomorrowIst);
}

export function getTopicPoolStats(): TopicPoolStats {
  const state = loadStoreState();
  const usedSet = new Set<string>(state.usedTopicKeys || []);
  const usedCount = Math.min(TOTAL_SYLLABUS_TOPICS, usedSet.size);
  return {
    totalTopics: TOTAL_SYLLABUS_TOPICS,
    usedCount,
    remainingCount: Math.max(0, TOTAL_SYLLABUS_TOPICS - usedCount),
    cycleCount: state.topicCycleCount || 1,
  };
}

export function getApprovedDailyAiIdsForTopic(
  state: PersistentAIStoreState,
  assignedTopic: StudyPlanDay
): string[] {
  const pinnedIds = state.syllabusOverrides[assignedTopic.dayKey]?.dailyMcqIds || [];
  if (pinnedIds.length === 0) return [];
  const approvedSet = new Set(
    state.questionPool
      .filter((q) => q.reviewStatus === 'approved')
      .map((q) => q.id)
  );
  return pinnedIds.filter((id) => approvedSet.has(id));
}

export const DAILY_AI_RETRY_COOLDOWN_MS = 3 * 60 * 1000;

export function needsDailyAiGeneration(
  state: PersistentAIStoreState,
  istDate: string,
  assignedTopic: StudyPlanDay,
  nowMs: number = Date.now(),
  forceGenerate = false
): boolean {
  if (!isActiveProviderKeyConfigured()) {
    return false;
  }
  if (forceGenerate) {
    return true;
  }
  if (!state.aiConfig.autoGenerateDailyExam) {
    return false;
  }

  const targetCount = Math.max(10, Math.min(50, state.scheduleConfig.totalQuestions || 30));
  const meta = state.dailyPaperGenerationMeta?.[istDate];
  const existingPaper = state.dailyPapers[istDate];
  const approvedPinnedIds = getApprovedDailyAiIdsForTopic(state, assignedTopic);
  const paperAiCount = existingPaper
    ? existingPaper.questions.filter(
        (q) =>
          (q as Partial<AIMCQQuestion>).sourceType === 'ai_generated' &&
          (approvedPinnedIds.includes(q.id) ||
            normalizeTopicLabel(q.topic) === normalizeTopicLabel(assignedTopic.topic) ||
            normalizeTopicLabel(q.topic).includes(normalizeTopicLabel(assignedTopic.topic)))
      ).length
    : 0;

  if (
    meta &&
    meta.dayKey === assignedTopic.dayKey &&
    meta.status === 'complete' &&
    approvedPinnedIds.length >= Math.min(targetCount, meta.aiGeneratedCount) &&
    paperAiCount >= Math.min(targetCount, meta.aiGeneratedCount)
  ) {
    return false;
  }

  if (
    paperAiCount >= targetCount &&
    existingPaper?.description?.includes(assignedTopic.topic)
  ) {
    return false;
  }

  // Enforce a short retry cooldown for automatic ticks when a previous attempt ran for the same day/topic
  if (meta && meta.dayKey === assignedTopic.dayKey && meta.lastAttemptAt) {
    const elapsed = nowMs - Date.parse(meta.lastAttemptAt);
    if (Number.isFinite(elapsed) && elapsed >= 0 && elapsed < DAILY_AI_RETRY_COOLDOWN_MS) {
      return false;
    }
  }

  return true;
}

